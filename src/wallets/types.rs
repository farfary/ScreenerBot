/// Wallet information (without private key)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Wallet {
    /// Unique database ID
    pub id: i64,
    /// User-friendly name
    pub name: String,
    /// Solana public key (base58)
    pub address: String,
    /// Role in the system
    pub role: WalletRole,
    /// How the wallet was created
    pub wallet_type: WalletType,
    /// Creation timestamp
    pub created_at: DateTime<Utc>,
    /// Last time wallet was used for a transaction
    pub last_used_at: Option<DateTime<Utc>>,
    /// User notes/description
    pub notes: Option<String>,
    /// Whether wallet is active (not archived/deleted)
    pub is_active: bool,
}

impl Wallet {
    /// Check if this is the main wallet
    pub fn is_main(&self) -> bool {
        self.role == WalletRole::Main
    }

    /// Check if wallet can be used for operations
    pub fn is_usable(&self) -> bool {
        self.is_active && self.role != WalletRole::Archive
    }
}

/// Summary of all wallets for dashboard
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WalletsSummary {
    /// Total number of wallets
    pub total_count: u32,
    /// Number of active wallets
    pub active_count: u32,
    /// Main wallet address (if any)
    pub main_wallet: Option<String>,
    /// Main wallet name (if any)
    pub main_wallet_name: Option<String>,
    /// Total SOL across all active wallets (placeholder, populated by balance fetching)
    pub total_native: f64,
}

/// Response after exporting a wallet
#[derive(Debug, Clone, Serialize)]
pub struct ExportWalletResponse {
    /// Wallet address
    pub address: String,
    /// Private key in base58 format
    pub private_key: String,
    /// Warning message
    pub warning: String,
}

#[cfg(test)]
mod label_tests {
    use super::WalletType;

    /// Catalog key of the label for each wallet type. The match is exhaustive, so
    /// a new variant fails to compile until it is mapped here and in
    /// `WALLET_TYPE_LABELS` (pages/wallets/renderers.js).
    fn label_key(wallet_type: &WalletType) -> &'static str {
        match wallet_type {
            WalletType::Generated => "wallets-type-generated",
            WalletType::Imported => "wallets-type-imported",
            WalletType::Migrated => "wallets-type-migrated",
        }
    }

    #[test]
    fn wallet_type_labels_exist_in_the_catalog() {
        for wallet_type in [
            WalletType::Generated,
            WalletType::Imported,
            WalletType::Migrated,
        ] {
            let id = serde_json::to_value(&wallet_type).unwrap();
            let key = label_key(&wallet_type);
            assert_eq!(
                key.strip_prefix("wallets-type-"),
                id.as_str(),
                "key does not follow the serialized id {id}"
            );
            assert_ne!(crate::i18n::format_en(key, None), key, "missing {key}");
        }
    }
}
