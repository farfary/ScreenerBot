/// Log tag definitions for module categorization
///
/// This is moved from logger.rs to keep the module organized.
/// Tags identify which part of the system is logging.
use colored::*;

#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum LogTag {
    Monitor,
    Trader,
    Wallet,
    System,
    Connectivity,
    Pool,
    PoolService,
    PoolCalculator,
    PoolDiscovery,
    PoolFetcher,
    PoolAnalyzer,
    PoolCache,
    PoolDecoder,
    Blacklist,
    Discovery,
    Filtering,
    Api,
    Profit,
    PriceService,
    SolPrice,
    Rpc,
    Ohlcv,
    Decimals,
    Cache,
    Swap,
    Entry,
    RlLearn,
    Summary,
    Tokens,
    Transactions,
    Websocket,
    Positions,
    AI,
    Unknown,
    Security,
    Webserver,
    Notifications,
    Telegram,
    Test,
    Tools,
    Other(String),
}

impl LogTag {
    /// Convert tag to debug key for config lookup
    pub fn to_debug_key(&self) -> String {
        match self {
            LogTag::Monitor => "monitor".to_owned(),
            LogTag::Trader => "trader".to_owned(),
            LogTag::Wallet => "wallet".to_owned(),
            LogTag::System => "system".to_owned(),
            LogTag::Connectivity => "connectivity".to_owned(),
            LogTag::Pool => "pool".to_owned(),
            LogTag::PoolService => "pool_service".to_owned(),
            LogTag::PoolCalculator => "pool_calculator".to_owned(),
            LogTag::PoolDiscovery => "pool_discovery".to_owned(),
            LogTag::PoolFetcher => "pool_fetcher".to_owned(),
            LogTag::PoolAnalyzer => "pool_analyzer".to_owned(),
            LogTag::PoolCache => "pool_cache".to_owned(),
            LogTag::PoolDecoder => "pool_decoder".to_owned(),
            LogTag::Blacklist => "blacklist".to_owned(),
            LogTag::Discovery => "discovery".to_owned(),
            LogTag::Filtering => "filtering".to_owned(),
            LogTag::Api => "api".to_owned(),
            LogTag::Profit => "profit".to_owned(),
            LogTag::PriceService => "price_service".to_owned(),
            LogTag::SolPrice => "sol_price".to_owned(),
            LogTag::Rpc => "rpc".to_owned(),
            LogTag::Ohlcv => "ohlcv".to_owned(),
            LogTag::Decimals => "decimals".to_owned(),
            LogTag::Cache => "cache".to_owned(),
            LogTag::Swap => "swap".to_owned(),
            LogTag::Entry => "entry".to_owned(),
            LogTag::RlLearn => "rl_learn".to_owned(),
            LogTag::Summary => "summary".to_owned(),
            LogTag::Tokens => "tokens".to_owned(),
            LogTag::Transactions => "transactions".to_owned(),
            LogTag::Websocket => "websocket".to_owned(),
            LogTag::Positions => "positions".to_owned(),
            LogTag::AI => "ai".to_owned(),
            LogTag::Unknown => "unknown".to_owned(),
            LogTag::Security => "security".to_owned(),
            LogTag::Webserver => "webserver".to_owned(),
            LogTag::Notifications => "notifications".to_owned(),
            LogTag::Telegram => "telegram".to_owned(),
            LogTag::Test => "test".to_owned(),
            LogTag::Tools => "tools".to_owned(),
            LogTag::Other(ref s) => s.to_lowercase(),
        }
    }

    /// Get plain text representation (for file logging)
    pub fn to_plain_string(&self) -> &'static str {
        match self {
            LogTag::Monitor => "MONITOR",
            LogTag::Trader => "TRADER",
            LogTag::Wallet => "WALLET",
            LogTag::System => "SYSTEM",
            LogTag::Connectivity => "CONNECT",
            LogTag::Pool => "POOL",
            LogTag::PoolService => "POOLSVC",
            LogTag::PoolCalculator => "POOLCALC",
            LogTag::PoolDiscovery => "POOLDISC",
            LogTag::PoolFetcher => "POOLFETCH",
            LogTag::PoolAnalyzer => "POOLANLZ",
            LogTag::PoolCache => "POOLCACH",
            LogTag::PoolDecoder => "POOLDEC",
            LogTag::Blacklist => "BLACKLIST",
            LogTag::Discovery => "DISCOVER",
            LogTag::Filtering => "FILTER",
            LogTag::Api => "API",
            LogTag::Profit => "PROFIT",
            LogTag::PriceService => "PRICE",
            LogTag::SolPrice => "SOLPRICE",
            LogTag::Rpc => "RPC",
            LogTag::Ohlcv => "OHLCV",
            LogTag::Decimals => "DECIMALS",
            LogTag::Cache => "CACHE",
            LogTag::Swap => "SWAP",
            LogTag::Entry => "ENTRY",
            LogTag::RlLearn => "RL_LEARN",
            LogTag::Summary => "SUMMARY",
            LogTag::Tokens => "TOKENS",
            LogTag::Transactions => "TX",
            LogTag::Websocket => "WS",
            LogTag::Positions => "Positions",
            LogTag::AI => "AI",
            LogTag::Unknown => "UNKNOWN",
            LogTag::Security => "SECURITY",
            LogTag::Webserver => "WEBSERVER",
            LogTag::Notifications => "NOTIFY",
            LogTag::Telegram => "TELEGRAM",
            LogTag::Test => "TEST",
            LogTag::Tools => "TOOLS",
            LogTag::Other(_) => "OTHER",
        }
    }
}

